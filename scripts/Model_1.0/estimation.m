                data.i_star.Data(2:end),...
                data.i_star.Data(1:end-1),...
                'VariableNames',...
                {'i_star', 'i_star_lag'}...
                );

% Estimating the equation
Eq_i_star = fitlm(FIRTbl,'i_star~i_star_lag', 'Intercept', false);
         
% Coefficients
% alpha_2,1 = 0.866057930338393

