%{ 
Scritp for estimating the model version 1.1 equation by equation using
OLS
 %}

% Load the "ola" variable
data = databank.fromCSV('data/model_1.0/ola_variables.csv');

% We will not create a function to estimate each equation; insted we,
% will estimate the equation by building its table and then estimate the
% equation, since this process is cleare and easy to follow. All equations
% are estimated from 2009Q1 to 2025Q3

%% 1) Foreing economic growth %%%%%
% building its table
FEGTbl = table(...
                data.GDP_star.Data(2:end),...
                data.GDP_star.Data(1:end-1),...
                'VariableNames',...
                {'GDP_star', 'GDP_star_lag'}...
                );

% Estimating the equcation
Eq_Y_star = fitlm(FEGTbl,'GDP_star~GDP_star_lag', 'Intercept', false);

% Coefficients
% alpha_1,1 = 0.754361330238206

%% 2) Foreing policy interest rate %%%%%
