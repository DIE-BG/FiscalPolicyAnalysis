                data.DPI.Data(2:end),...
                data.DPI.Data(1:end-1),...
                data.DPE.Data(1:end-1),...
                data.GFun.Data(1:end-1) + data.IPub.Data(1:end-1) - data.IngT.Data(1:end-1),...
                'VariableNames',...
                {'DPI', 'DPI_lag', 'DPE_lag', 'Def_lag'}...
